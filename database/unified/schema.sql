CREATE TABLE vendedor (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  uid text NOT NULL,
  nombre_negocio VARCHAR(160) NOT NULL,
  slug VARCHAR(180) NOT NULL,
  rnc VARCHAR(11) NULL,
  rnc_verificado smallint NOT NULL DEFAULT 0,
  logo_url VARCHAR(500) NULL,
  descripcion TEXT NULL,
  provincia VARCHAR(80) NULL,
  municipio VARCHAR(80) NULL,
  latitud DECIMAL(10,7) NULL,
  longitud DECIMAL(10,7) NULL,
  estado text NOT NULL DEFAULT 'pendiente',
  motivo_estado VARCHAR(500) NULL,
  aprobado_por_uid text NULL,
  aprobado_en timestamptz NULL,
  rating_promedio DECIMAL(3,2) NOT NULL DEFAULT 0.00,
  total_resenas bigint NOT NULL DEFAULT 0,
  total_productos bigint NOT NULL DEFAULT 0,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  CONSTRAINT uq_vendedor_uid UNIQUE (uid),
  CONSTRAINT uq_vendedor_slug UNIQUE (slug),
  CONSTRAINT ck_vendedor_rating CHECK (rating_promedio BETWEEN 0 AND 5),
  CHECK (id >= 0),
  CHECK (rnc_verificado IN (0,1)),
  CHECK (estado IN ('pendiente','aprobado','rechazado','suspendido')),
  CHECK (total_resenas >= 0),
  CHECK (total_productos >= 0)
);
CREATE INDEX ix_vendedor_estado ON vendedor (estado);
