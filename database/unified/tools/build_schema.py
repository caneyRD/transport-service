"""Rebuild the consolidated PostgreSQL baseline from the frozen source files."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def split_sql(s, delimiter=','):
    result, start, depth, quoted = [], 0, 0, False
    i = 0
    while i < len(s):
        c = s[i]
        if c == "'":
            if quoted and i + 1 < len(s) and s[i + 1] == "'":
                i += 2
                continue
            quoted = not quoted
        if not quoted:
            depth += (c == '(') - (c == ')')
            if c == delimiter and depth == 0:
                result.append(s[start:i].strip()); start = i + 1
        i += 1
    if s[start:].strip(): result.append(s[start:].strip())
    return result

tables = {}
pieces = ["-- BANEY consolidated baseline v1. PostgreSQL 17+. Fresh database only.\nBEGIN;\nSET TIME ZONE 'UTC';\n"]
for p in sorted((ROOT / 'sources').glob('0*.sql')):
    schema = 'baney_' + p.stem.split('_')[1]
    s = re.sub(r'--[^\n]*', '', p.read_text(encoding='utf-8'))
    s = re.sub(r"COMMENT\s+'(?:[^']|'')*'", '', s)
    pieces.append(f'CREATE SCHEMA {schema};\nSET search_path TO {schema}, public;\n')
    for stmt in split_sql(s, ';'):
        if stmt.startswith(('CREATE DATABASE', 'USE ', 'INSERT INTO')): continue
        if stmt.startswith('CREATE TABLE'):
            m = re.match(r'CREATE TABLE (\w+)\s*\((.*)\)\s*ENGINE=InnoDB', stmt, re.S)
            if not m: raise ValueError(stmt)
            name, body = m.groups(); cols, indexes, checks = [], [], []
            tables[f'{schema}.{name}'] = []
            for item in split_sql(body):
                item = re.sub(r'\s+', ' ', item)
                if item.startswith('FULLTEXT KEY'):
                    idx = item.split()[2]
                    indexes.append(f"CREATE INDEX {idx} ON {name} USING gin (to_tsvector('spanish', coalesce(nombre,'') || ' ' || coalesce(descripcion,'')));")
                    continue
                if item.startswith('KEY '):
                    item = re.sub(r'(\w+)\(191\)', r'\1', item)
                    idx, fields = re.match(r'KEY (\w+) (.*)', item).groups()
                    indexes.append(f'CREATE INDEX {idx} ON {name} {fields};'); continue
                if item.startswith('UNIQUE KEY '):
                    item = re.sub(r'UNIQUE KEY (\w+)', r'CONSTRAINT \1 UNIQUE', item)
                elif not item.startswith(('CONSTRAINT ', 'PRIMARY KEY')):
                    col = item.split()[0]; tables[f'{schema}.{name}'].append(col)
                    if 'UNSIGNED' in item: checks.append(f'CHECK ({col} >= 0)')
                    if 'TINYINT(1)' in item: checks.append(f'CHECK ({col} IN (0,1))')
                    enum = re.search(r'ENUM\((.*?)\)', item)
                    if enum:
                        checks.append(f'CHECK ({col} IN ({enum.group(1)}))')
                        item = item[:enum.start()] + 'text' + item[enum.end():]
                    item = re.sub(r'\bCHAR\(26\)', 'text', item)
                    item = re.sub(r'\bTINYINT(?:\(1\))?', 'smallint', item)
                    item = re.sub(r'\bINT UNSIGNED\b', 'bigint', item)
                    item = re.sub(r'\bSMALLINT UNSIGNED\b', 'integer', item)
                    item = item.replace(' UNSIGNED', '')
                    item = item.replace('NOT NULL AUTO_INCREMENT', 'GENERATED BY DEFAULT AS IDENTITY')
                    item = re.sub(r'\bDATETIME\(3\)', 'timestamptz', item)
                    item = re.sub(r'\bJSON\b', 'jsonb', item)
                    item = re.sub(r'\bVARBINARY\(\d+\)', 'bytea', item)
                    item = item.replace(' ON UPDATE CURRENT_TIMESTAMP(3)', '')
                    item = item.replace(' AS (', ' GENERATED ALWAYS AS (')
                    if col == 'trip_uid': item = item.replace('text', 'uuid', 1)
                item = re.sub(r'\((\w+) IS NOT NULL\)(?=\s*[+=])', r'(\1 IS NOT NULL)::int', item)
                cols.append(item)
            pieces.append(f'CREATE TABLE {name} (\n  ' + ',\n  '.join(cols + checks) + '\n);\n' + '\n'.join(indexes) + '\n')
        else:
            stmt = re.sub(r"DATE_FORMAT\(([^,]+), '%Y%m'\)", r"to_char(\1, 'YYYYMM')", stmt)
            stmt = re.sub(r"DATE_FORMAT\(([^,]+), '%Y-%m'\)", r"to_char(\1, 'YYYY-MM')", stmt)
            pieces.append(stmt + ';\n')

transport = (ROOT / 'sources/transport.sql').read_text(encoding='utf-8')
transport = re.sub(r'--[^\n]*', '', transport)
transport = transport.replace('BEGIN;', '').replace('COMMIT;', '')
transport = re.sub(r'uuid PRIMARY KEY', 'uuid PRIMARY KEY DEFAULT gen_random_uuid()', transport)
transport = transport.replace("(status <> 'COUNTERED' OR parent_offer_id IS NOT NULL) AND", '(parent_offer_id IS NULL) = (proposed_by IS NULL) AND')
transport = transport.replace('WHERE idempotency_key IS NOT NULL AND deleted_at IS NULL', 'WHERE idempotency_key IS NOT NULL')
pieces.append(transport)
pieces.append((ROOT / 'modules.sql').read_text(encoding='utf-8'))

# Cross-context foreign keys: all targets exist before these run. Text IDs preserve
# legacy Auth IDs and ULIDs; transport native IDs remain UUIDs.
links = []
user_cols = {'usuario_uid','comprador_uid','autor_uid','actor_uid','admin_uid','aprobado_por_uid',
             'solicitante_uid','resuelta_por_uid','subida_por_uid','autorizado_por_uid','abierta_por_uid',
             'receptor_uid','creado_por_uid','cerrado_por_uid','ejecutado_por_uid','solicitado_por_uid',
             'emisor_uid','obligado_uid','beneficiario_uid','titular_uid'}
targets = {'vendedor_uid':('baney_catalog.vendedor','uid'), 'variante_uid':('baney_catalog.variante','uid'),
           'producto_uid':('baney_catalog.producto','uid'), 'pedido_uid':('baney_order.pedido','uid'),
           'carrito_uid':('baney_cart.carrito','uid'), 'direccion_uid':('profiles.addresses','id'),
           'cotizacion_uid':('baney_cart.cotizacion_transporte','uid'), 'trip_uid':('transport.trips','id'),
           'payment_uid':('payments.payment_intents','id'), 'payment_refund_uid':('payments.refunds','id'),
           'nota_credito_uid':('baney_billing.factura','uid'), 'factura_uid':('baney_billing.factura','uid'),
           'liquidacion_uid':('baney_billing.liquidacion','uid'), 'payout_uid':('baney_caja.payout','uid'),
           'disputa_uid':('support.disputes','id'), 'fusionado_en_uid':('baney_cart.carrito','uid')}
for table, columns in tables.items():
    for col in columns:
        target = ('identity.users','id') if col in user_cols else targets.get(col)
        if target: links.append((table,col,*target))
links += [('baney_catalog.vendedor','uid','identity.users','id'),
          ('transport.transport_requests','requester_id','identity.users','id'),
          ('transport.driver_profiles','user_id','identity.users','id'),
          ('transport.vehicles','owner_id','identity.users','id'),
          ('transport.transport_offers','carrier_id','identity.users','id'),
          ('baney_billing.comision','liquidacion_id','baney_billing.liquidacion','id'),
          ('baney_caja.movimiento','conciliacion_id','baney_caja.conciliacion','id'),
          ('baney_caja.saldo_cuenta','ultimo_movimiento_id','baney_caja.movimiento','id'),
          ('baney_caja.auditoria','cuenta_id','baney_caja.cuenta','id')]
for i,(table,col,target,key) in enumerate(links,1):
    pieces.append(f'ALTER TABLE {table} ADD CONSTRAINT fk_unified_{i:03} FOREIGN KEY ({col}) REFERENCES {target} ({key}) DEFERRABLE INITIALLY IMMEDIATE;\n')
# Typed generated references replace unenforced polymorphic links. Applications
# still write the source tipo/uid pair; PostgreSQL derives and validates the FK.
ref_targets = {'pedido':('baney_order.pedido','uid','text'), 'suborden':('baney_order.suborden','uid','text'),
 'viaje':('transport.trips','id','uuid'), 'factura':('baney_billing.factura','uid','text'),
 'comision':('baney_billing.comision','uid','text'), 'liquidacion':('baney_billing.liquidacion','uid','text'),
 'payout':('baney_caja.payout','uid','text'), 'devolucion':('baney_order.devolucion','uid','text'),
 'reembolso':('payments.refunds','id','text'), 'conciliacion':('baney_caja.conciliacion','uid','text'),
 'reserva':('baney_inventory.reserva','uid','text'), 'carrito':('baney_cart.carrito','uid','text')}
poly = {
 'baney_inventory.reserva': ('origen_tipo','origen_uid',['carrito','pedido']),
 'baney_inventory.movimiento_stock': ('referencia_tipo','referencia_uid',['pedido','suborden','devolucion','reserva']),
 'baney_billing.factura': ('referencia_tipo','referencia_uid',['pedido','suborden','viaje','comision','liquidacion']),
 'baney_billing.comision': ('referencia_tipo','referencia_uid',['suborden','viaje']),
 'baney_billing.liquidacion_linea': ('referencia_tipo','referencia_uid',['suborden','viaje','comision','devolucion']),
 'baney_caja.movimiento': ('referencia_tipo','referencia_uid',['pedido','suborden','viaje','factura','comision','liquidacion','payout','devolucion','reembolso','conciliacion']),
}
for table,(kind,ref,values) in poly.items():
    for value in values:
        target,key,typ = ref_targets[value]
        pieces.append(f"ALTER TABLE {table} ADD COLUMN ref_{value} {typ} GENERATED ALWAYS AS (CASE WHEN {kind}='{value}' THEN {ref}::{typ} END) STORED REFERENCES {target}({key});\n")
    literals=','.join("'"+v+"'" for v in values)
    pieces.append(f'ALTER TABLE {table} ADD CONSTRAINT ck_typed_reference CHECK ({kind} NOT IN ({literals}) OR {ref} IS NOT NULL);\n')
pieces.append((ROOT / 'integrity.sql').read_text(encoding='utf-8'))
pieces.append("\nSET search_path TO platform, public;\nINSERT INTO platform.schema_versions(version, description) VALUES ('001', 'BANEY unified baseline');\nCOMMIT;\n")
(ROOT/'schema.sql').write_text('\n'.join(pieces), encoding='utf-8', newline='\n')
print(f'Generated schema.sql; {len(tables)} imported MySQL tables; {len(links)} added direct foreign keys.')
